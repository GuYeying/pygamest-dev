def fps_view(eye, yaw_deg, pitch_deg):
    yaw = M.radians(yaw_deg)
    pitch = M.radians(pitch_deg)
    fx = M.cos(pitch) * M.sin(yaw)
    fy = M.sin(pitch)
    fz = -M.cos(pitch) * M.cos(yaw)
    f = (fx, fy, fz)                       # 前向（单位——三角恒等式保证）
    up0 = (0.0, 1.0, 0.0)
    s0 = (fy * up0[2] - fz * up0[1],
          fz * up0[0] - fx * up0[2],
          fx * up0[1] - fy * up0[0])       # right = f × up（模 = cos(pitch)
                                            # ≠ 1——**必须归一化**，否则
                                            # pitch 越大横竖缩放越失配）
    sn = (s0[0] * s0[0] + s0[1] * s0[1] + s0[2] * s0[2]) ** 0.5
    s = (s0[0] / sn, s0[1] / sn, s0[2] / sn)
    u = (s[1] * fz - s[2] * fy,
         s[2] * fx - s[0] * fz,
         s[0] * fy - s[1] * fx)            # true up = s × f（s⊥f 双单位
                                            # → u 自动单位）
    ex, ey, ez = eye
    # 视图基（行主视觉——标准 view 行向量）→ 列主展开（from_cols_array
    # 列主序契约：out[c*4+r] = m[r*4+c]）
    m = [
        s[0], s[1], s[2], -s[0] * ex - s[1] * ey - s[2] * ez,
        u[0], u[1], u[2], -u[0] * ex - u[1] * ey - u[2] * ez,
        -f[0], -f[1], -f[2], f[0] * ex + f[1] * ey + f[2] * ez,
        0.0, 0.0, 0.0, 1.0,
    ]
    cols = [m[r * 4 + c] for c in range(4) for r in range(4)]
    return M.mat4_from_cols_array(cols)


async def main():
    pygame.display.set_caption("fluid_test")
    screen = pygame.display.set_mode((800, 600))
    cjk = pygame.font.Font("cjk", 15)
    ac = pygame.render.access()
    frame = 0
    _fail = []

    def st(name, cond):
        if cond:
            print("[fluid-test] PASS", name)
        else:
            _fail.append(name)
            print("[fluid-test] FAIL", name)

    # ── solid 世界（rapier 静态刚体——**碰撞主角**）──
    # 地面（大平面 cuboid）+ 斜面（旋转 22°——+x 端翘起；水柱从高端倒下
    # 沿面滑落。耦合注册按 collider 位姿每步重采样——旋转刚体开箱即用）
    solid = pp.PhysicsWorld3D(gravity=(0, -9.81, 0))
    solid.insert(
        pp.RigidBodyBuilder3D("fixed", translation=(0, -0.25, 0)),
        pp.ColliderBuilder3D("cuboid", hx=10.0, hy=0.25, hz=10.0, friction=0.5),
    )
    solid.insert(
        pp.RigidBodyBuilder3D(
            "fixed", translation=(0.5, 1.2, 0),
            rotation=(0.0, 0.0, 0.35)),   # rz≈20°（rapier 欧拉角弧度）
        pp.ColliderBuilder3D("cuboid", hx=1.6, hy=0.12, hz=1.2, friction=0.1),
    )
    solid.step_frame(1.0 / 60.0)   # 时序契约（查询前必步进一次）

    # ── fluid 世界（salva DFSPH——粒子半径 0.1）──
    fw = pp.FluidWorld(particle_radius=0.1)
    st("FluidWorld 构造", fw is not None)
    st("particle_radius 0.1", abs(fw.particle_radius() - 0.1) < 1e-6)

    # 水柱：0.7×0.8×0.7 方块水（spacing 0.2 → 36 粒子），位于斜面
    # 高端（+x 翘起端）上方——倒下后沿斜面滑向 -x 端摊开静置
    fh = fw.add_fluid_cuboid((1.2, 2.6, -0.35), (0.7, 0.8, 0.7))
    handles = [fh]   # 全句柄聚合（空格注水 = 新 fluid 句柄——渲染枚举全量）
    n = fw.fluid_particle_count(fh)
    st(f"水柱粒子数 {n} > 30", n > 30)

    # ── instanced 渲染管线（粒子 → GPU 球矩阵通路）──
    cam_buf = ac.buffer(64, label="cam_buf")
    sphere_mesh = ac.mesh(["float32x3", "float32x3"], SPHERE, label="sphere_mesh")
    shader = ac.shader(WGSL, label="fluid_shader")

    # 相机（斜 45° 俯瞰斜面场景）
    cam = pygame.render.game_camera_perspective(
        50.0, W, H, W, H, 0.1, 100.0)
    cam = cam.with_view(fps_view((-4.2, 3.4, 5.8), 36.0, -19.0))
    screen.set_camera(cam)
    pygame.render.write_camera_mvp(cam_buf, cam.mvp())  # 静态相机恒定

    # 每粒子独立 model uniform + bind（记录-回放模型：write 立即生效、
    # draw 回放时读 buffer——共享 buf = 全部粒子叠最后粒子位置；粒子数
    # 固定惰性扩容，空格注水追加时自动跟上）
    particle_uniforms = []

    def ensure_particle_uniforms(count):
        while len(particle_uniforms) < count:
            i = len(particle_uniforms)
            b = ac.buffer(64, label=f"fluid_model_{i}")
            bd = ac.bind_group([
                (0, "uniform", cam_buf),
                (1, "uniform", b),
            ], label=f"fluid_model_bind_{i}")
            particle_uniforms.append((b, bd))

    pipe = None   # 首帧粒子数就绪后建（pipeline 需 bind_group 模板）

    # solid 调试线（rapier 线框——DebugLinesRenderer3D + collect3d）
    dbg_draw = pp.DebugDraw3D()
    pixel_cam = pygame.render.game_camera_ortho(800, 600, 800, 600)
    dbg_renderer = pp.DebugLinesRenderer3D()  # 相机由 set_mvp 直写

    solid_debug = True   # T 键切换（默认开——碰撞对齐目视验收）
    drops = []           # F 键投放的 dynamic 刚体（×流体耦合验证）

    # 刚体渲染（cube mesh 复用 fluid 管线 layout——pos3+nrm3 同构；
    # per-body uniform 惰性扩容同粒子同款）
    cube_mesh = ac.mesh(["float32x3", "float32x3"], CUBE, label="cube_mesh")
    block_uniforms = []

    def ensure_block_uniforms(count):
        while len(block_uniforms) < count:
            i = len(block_uniforms)
            b = ac.buffer(64, label=f"block_model_{i}")
            bd = ac.bind_group([
                (0, "uniform", cam_buf),
                (1, "uniform", b),
            ], label=f"block_model_bind_{i}")
            block_uniforms.append((b, bd))

    while True:
        for e in pygame.event.get():
            if e.type == pygame.event.QUIT:
                return
            if e.type == pygame.event.KEYDOWN:
                if e.key == pygame.key.K_ESCAPE:
                    return
                if e.key == pygame.key.K_t:
                    solid_debug = not solid_debug
                if e.key == pygame.key.K_SPACE:
                    # 注入一波新流体（斜面高端上方随机位置；新句柄入
                    # handles 聚合——渲染枚举全量）
                    fh2 = fw.add_fluid_cuboid(
                        (1.1 + (frame % 5) * 0.08, 3.4, -0.3),
                        (0.5, 0.4, 0.5))
                    handles.append(fh2)
                    print(f"[fluid-test] 注入流体 handle={fh2}")
                if e.key == pygame.key.K_f:
                    # 投放 dynamic 刚体（**dynamic×流体耦合验证**——
                    # bb46a1b 开放：DC 位置投影推开粒子、刚体沉底）
                    x = 0.6 + (frame % 4) * 0.35
                    h = solid.insert(
                        pp.RigidBodyBuilder3D(
                            "dynamic", translation=(x, 2.6, 0.0)),
                        pp.ColliderBuilder3D("cuboid",
                                             hx=0.15, hy=0.15, hz=0.15))[0]
                    drops.append(h)
                    print(f"[fluid-test] 投放方块 handle={h} @x={x}")
                if e.key == pygame.key.K_g:
                    cur = pp.scheduler_status().get("fluid")
                    pp.scheduler_enable("fluid", not cur)
                    print(f"[fluid-test] 调度器 fluid → {not cur}")

        # 物理（solid + fluid 耦合步进——**本案例核心**：fluid.step 收
        # solid 世界，cuboid collider 增量注册为 salva 边界，粒子被
        # 静态刚体推开；调度器 fluid 关闭时 fluid 侧暂停/solid 照常）
        solid.step_frame(1.0 / 60.0)
        fw.step(1.0 / 60.0, solid)

        if frame == 1:
            # 耦合注册验证：地面 + 斜面两个 cuboid collider → salva 边界
            bc = fw.boundary_count()
            st(f"耦合边界注册 {bc} >= 2", bc >= 2)

        positions = []
        for h in handles:
            p, _v = fw.fluid_particles(h)
            positions.extend(p)
        count = len(positions) // 3
        ensure_particle_uniforms(count)
        if pipe is None and count > 0:
            model_buf = ac.buffer(64, label="model_template")
            bind = ac.bind_group([
                (0, "uniform", cam_buf),
                (1, "uniform", model_buf),
            ], label="fluid_bind")
            pipe = ac.pipeline(shader, sphere_mesh, [bind], cull="back",
                               blend="opaque", depth_mode="standard",
                               depth_write=True, label="fluid_pipe")

        with screen.render() as rt:
            rt.fill((16, 20, 30))
            with screen.raw_render(depth=True) as p:
                # ① solid 线框（T 切换——rapier collider 线框叠加，与
                # 主相机 set_mvp 绝对对齐）
                if solid_debug:
                    sink = pp.LineSink3D()
                    pp.collect3d(solid, dbg_draw, sink)
                    dbg_renderer.set_mvp(cam.mvp())
                    rt.draw_debug_3d(dbg_renderer, sink)
                # ② 流体粒子球（每帧逐粒子 draw——百级粒子可承受）
                for i in range(count):
                    x = positions[i * 3]
                    y = positions[i * 3 + 1]
                    z = positions[i * 3 + 2]
                    buf_i, bind_i = particle_uniforms[i]
                    ac.write_buffer(buf_i, M.mat4_translation(x, y, z))
                    p.set_pipeline(pipe)
                    p.set_bind_group(0, bind_i)
                    p.draw_mesh(sphere_mesh)
                # ③ dynamic 刚体立方体（F 投放——同管线 layout 直绘
                # cube_mesh；DC 单向耦合：粒子被推开、刚体沉底）
                if drops:
                    ensure_block_uniforms(len(drops))
                    for i, h in enumerate(drops):
                        x, y, z = solid.translation(h)
                        buf_i, bind_i = block_uniforms[i]
                        ac.write_buffer(buf_i, M.mat4_translation(x, y, z))
                        p.set_pipeline(pipe)
                        p.set_bind_group(0, bind_i)
                        p.draw_mesh(cube_mesh)

            # HUD（段级显式像素相机——v3.1 全显式：米制相机下像素 UI
            # 须显式切段声明像素域，画毕 clear_camera 交还）
            pygame.gfxdraw.set_camera(rt, pixel_cam)
            pygame.gfxdraw.set_transform(rt, M.mat4_translation(-388, 288, 0))
            pygame.gfxdraw.draw_surface(rt, cjk.render(
                f"[fluid] 粒子 {count} 刚体 {len(drops)} | T solid线框={solid_debug} "
                f"空格=注水 F=投放刚体", True, (200, 210, 230)))
            pygame.gfxdraw.set_transform(rt, M.mat4_translation(-388, 268, 0))
            pygame.gfxdraw.draw_surface(rt, cjk.render(
                f"调度器: {pp.scheduler_status()}（G 键切 fluid 开关）",
                True, (180, 200, 180)))
            pygame.gfxdraw.clear_camera(rt)

        pygame.display.flip()
        if frame == 60:
            st("60 帧刚体×流体耦合渲染稳定", True)
        if frame == 300:
            pos, vel = fw.fluid_particles(fh)
            n3 = len(pos)
            mn_y = min(pos[1::3]) if n3 else -99.0
            mn_x = min(pos[0::3]) if n3 else 99.0
            mx_s = max((vel[i]**2 + vel[i+1]**2 + vel[i+2]**2) ** 0.5
                       for i in range(0, len(vel), 3)) if n3 else 99.0
            # 未穿地（地面顶 y=0；穿透 = 耦合碰撞无效）+ 滑落证据
            # （越过斜面中线 = 斜面碰撞交互发生；XSPH 粘性下水流呈
            # 蜂蜜状慢速成团滑落——300 帧到达斜面中部即证据，无粘形态
            # 早已摊开 -6）+ 静置衰减（能量正常耗散 = 物理合理非弹射）
            st(f"300 帧未穿地 min_y={mn_y:.3f} > -0.4", mn_y > -0.4)
            st(f"300 帧滑落交互 min_x={mn_x:.3f} < 0", mn_x < 0)
            st(f"300 帧静置衰减 max_spd={mx_s:.2f} < 2.0", mx_s < 2.0)
            st("300 帧粒子数据出口有效（句柄聚合）", n3 > 0 and count > 0)
            print("[fluid-test] SUMMARY",
                  "PASS" if not _fail else "FAIL " + str(_fail))
        if frame > 3600:
            return
        await pygame.tasks.yield_now()
        frame += 1
