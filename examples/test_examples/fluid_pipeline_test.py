# **无物理、固定相机、静止球体**——每帧内容逐位相同：任何累计痕迹/噪点
# 立即显形且可逐帧 BMP 对比。管线链 = fluid3d_game 同款三 pass：
#   ① 静止球群 → 离屏 fluid_surf（24bit 打包视深 rgb + alpha=1 覆盖，
#      背景 = 不透明哨兵 fill((0,0,0,1))）
#   ② 全屏 quad 合成 → 离屏 fluid_comp（7×7 bilateral + 法线重建 + 着色）
#   ③ 主屏 fill → gfxdraw blit fluid_comp → 线框 → HUD
# 打点：frame 120/121 各存一张 BMP（STARFISH_FB_BMP 逐帧覆写——用两次
